function runGenerator(tmpDir, ...args) {
    return execFileSync('node', [GENERATOR_PATH, ...args], {
        cwd: tmpDir,
        env: { ...process.env, CLAUDE_PROJECT_DIR: tmpDir },
        stdio: 'pipe',
        encoding: 'utf8'
    });
}

